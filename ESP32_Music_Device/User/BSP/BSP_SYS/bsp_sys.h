/**
 * @file bsp_sys.h
 * @brief 系统级 BSP 封装（时间基准、芯片信息等平台相关只读信息）
 * @author 李嘉图
 * @date 2026-06-18
 *
 * @note 本模块对平台接口做一层薄封装，上层通过 BSP_SYS_GetTickMs() 获取时间基准，
 *       不直接调用 esp_timer_get_time()。将来换平台或换 tick 源时只需改此文件。
 *
 *       ★ 与参考工程 bsp_sys.c 的对应关系：BSP_GetTickMs()（STM32 HAL_GetTick）
 *         → BSP_SYS_GetTickMs()（esp_timer_get_time / 1000）。
 *         带 SYS_ 前缀是为了和 BSP 层其它模块的命名风格统一，
 *         避免以后出现 BSP_WIFI_xxx 与 BSP_GetTickMs 混排时看不出归属。
 */

#ifndef __BSP_SYS_H__
#define __BSP_SYS_H__

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stdint.h>

/*==============================================================================
 * 时间基准
 *============================================================================*/
/**
 * @brief 获取系统滴答计数值（单位：ms）
 * @return 系统上电后的毫秒数（约 49 天回绕）
 * @note  基于 esp_timer_get_time()，精度微秒级，开销约 1us。
 *        ★ 使用无符号减法可安全处理回绕：
 *            if ((now - last) > timeout)   // 正确处理回绕
 */
uint32_t BSP_SYS_GetTickMs(void);

/**
 * @brief 获取系统时间（单位：us）
 * @return 系统上电后的微秒数
 * @note  用于需要微秒级时间戳的场合（如音频时间轴、I2S 节拍对齐）。
 */
uint64_t BSP_SYS_GetTickUs(void);

/*==============================================================================
 * 忙等延时
 *============================================================================*/
/**
 * @brief 微秒级忙等延时
 * @param us 延时微秒数
 * @note  会占用 CPU，不释放调度器。仅用于极短延时（< 1ms）或临界区内部。
 *        毫秒级延时请用 FreeRTOS 的 vTaskDelay，别用这个。
 */
void BSP_SYS_DelayUs(uint32_t us);

/*==============================================================================
 * 芯片信息（只读，用于启动日志）
 *============================================================================*/
/**
 * @brief 打印芯片型号、核心数、flash/PSRAM 容量、复位原因、MAC 地址
 * @note  启动时调一次，串口里能直接看到板子是不是预期的 N16R8。
 */
void BSP_SYS_PrintChipInfo(void);

#endif /* __BSP_SYS_H__ */
