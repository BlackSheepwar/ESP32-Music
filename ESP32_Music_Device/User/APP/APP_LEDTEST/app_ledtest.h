/**
 * @file app_ledtest.h
 * @brief LED 自检应用层（全引脚扫描，用来定位「灯到底接在哪个脚上」）
 * @author 李嘉图
 * @date 2026-06-26
 *
 * @note 用途：当你确认「程序跑了但灯不亮」时，最可能的原因是灯没接在代码假设的引脚上
 *       （本工程默认把 WiFi 状态灯放在 GPIO4，而模板原来接的是 GPIO1/GPIO2）。
 *       本模块把映射表里的输出脚逐个拉高 1 秒，并在串口打印当前正在点亮的引脚号 ——
 *       哪个脚亮，串口就停在哪个号上，不用万用表也能定位。
 *
 *       ★ 改 APP_LEDTEST_ENABLE 为 1 后编译烧录，观察完记得改回 0 ★
 */

#ifndef __APP_LEDTEST_H__
#define __APP_LEDTEST_H__

/*==============================================================================
 * 宏定义与常量
 *============================================================================*/
/**
 * @brief ★ LED 自检总开关 ★
 *
 *   0 = 关闭（默认）：不占用任何资源，WiFi 状态灯按正常逻辑工作
 *   1 = 打开：上电后先做扫描自检，做完自动切回正常模式
 *
 *   打开后串口会输出：
 *      阶段 1：映射表里的 14 个输出脚逐个点亮 1 秒 + 串口报 GPIO 号
 *      阶段 2：全部一起亮/灭 3 次（确认灯组整体和供电可用）
 *      阶段 3：扫描安全区里剩下的空闲 GPIO（每脚 1 秒），找出接在映射表之外的灯
 *      然后打印结论并交给正常逻辑
 */
#define APP_LEDTEST_ENABLE      0

/**
 * @brief 每个引脚点亮时长（毫秒）
 * @note  1 秒足够肉眼确认；想更快定位可以改成 300。
 */
#define APP_LEDTEST_STEP_MS     1000

/**
 * @brief 阶段 3 全引脚扫描的起始/结束引脚
 * @note  默认扫 0~21。其中 flash/PSRAM 占用的 11~17、已占用的按键/I2S/串口脚
 *        会在 app_ledtest.c 的 app_ledtest_is_reserved() 里被跳过。
 *        扫到没引出的脚不会有现象，也不会损坏任何东西。
 */
#define APP_LEDTEST_SWEEP_FROM  0
#define APP_LEDTEST_SWEEP_TO    21

/*==============================================================================
 * 接口
 *============================================================================*/
/**
 * @brief LED 自检任务
 * @param argument 未使用
 *
 * @note 设计成独立任务而不是插在 LED 任务里，原因有两个：
 *         1. 自检需要 vTaskDelay 阻塞式等待 1 秒，不能塞进 10ms 周期的服务函数
 *         2. 自检期间正常 LED 逻辑还在跑（WiFi 可能正在快闪），
 *            两者叠加时「常亮 1 秒」依然清晰可辨 —— 反而能同时确认
 *            「正常逻辑在跑」和「引脚号对不对」
 *
 *       APP_LEDTEST_ENABLE = 0 时本函数立刻退出，不建任何东西。
 */
void Task_LED_Test(void *argument);

#endif /* __APP_LEDTEST_H__ */
