/**
 * @file app_wifi_cfg.h
 * @brief WiFi 与状态指示灯配置（★ 要改 WiFi 就改这里 ★）
 * @author 李嘉图
 * @date 2026-06-26
 *
 * @note 本文件是「配置与代码分离」的落点：所有需要按现场环境调整的参数都集中在
 *       这一个头文件里，业务代码一个字都不用动。
 *
 *       ★★ 改 WiFi 账号密码：改下面 WIFI_SSID / WIFI_PASSWORD 两个宏 ★★
 *
 *       引脚不在这里配 —— 引脚在 BSP 层的映射表里
 *       （bsp_gpio.c 的 GPIO_HW_MAP、bsp_i2s.c 的 I2S_HW_MAP）。
 *       本文件只放「与硬件无关的策略参数」。
 */

#ifndef __APP_WIFI_CFG_H__
#define __APP_WIFI_CFG_H__

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 功能包含
#include "app_led_cfg.h"   /* WIFI_LED_ID 用的是逻辑 LED 编号 */

/*==============================================================================
 * ★★★ WiFi 连接参数（必须改）★★★
 *============================================================================*/
/**
 * @brief WiFi 名称（SSID）
 * @note  ★ 只支持 2.4GHz ★ ESP32 系列不支持 5GHz，如果路由器双频合一，
 *        请把 2.4G 的 SSID 单独分出来，否则会出现「能看到但连不上」。
 */
#define WIFI_SSID               "Lin_CF-E13"

/**
 * @brief WiFi 密码
 * @note  开放网络填空串 ""。WPA2-PSK / WPA3 混合模式均可用。
 */
#define WIFI_PASSWORD           "linforest1"

/**
 * @brief 固定信道（0 = 全信道扫描，推荐）
 * @note  知道路由器信道时填具体值（1~13）可以加快连接约 1~2 秒，
 *        但换路由器后必须同步修改，所以默认 0。
 */
#define WIFI_CHANNEL            0

/*==============================================================================
 * 连接与重连策略
 *============================================================================*/
/** @brief 单次连接尝试的超时（毫秒）。超过则判为本次失败并进入重试/退避 */
#define WIFI_CONNECT_TIMEOUT_MS 15000

/** @brief 连续失败多少次后进入「长退避」（表现为双闪） */
#define WIFI_MAX_RETRY          5

/** @brief 短重试的退避阶梯（毫秒）。第 n 次失败后等 RETRY_BACKOFF_MS[n] 再试 */
#define WIFI_RETRY_BACKOFF_MS   { 1000, 2000, 4000, 8000, 8000 }

/** @brief 长退避阶梯（毫秒）。失败次数用尽后按这个节奏继续试，永不放弃 */
#define WIFI_LONG_BACKOFF_MS    { 5000, 10000, 20000, 30000 }

/**
 * @brief 连接成功后的巡检周期（毫秒）
 * @note  WiFi 事件任务偶尔会漏报断线（尤其路由器重启、信道切换时），
 *        所以连上之后每 10 秒主动查一次，发现异常就重新走连接流程。
 */
#define WIFI_MONITOR_PERIOD_MS  10000

/*==============================================================================
 * 静态 IP（默认关闭）
 *============================================================================*/
/**
 * @brief 是否使用静态 IP
 * @note  0 = DHCP（推荐，家里/公司路由器都正常）；
 *        1 = 静态 IP，需要同时在下面填 IP/掩码/网关。
 *        调试期间如果 DHCP 拿不到地址，可以临时用静态 IP 绕过。
 */
#define WIFI_STATIC_IP_ENABLE   0

#define WIFI_STATIC_IP          "192.168.1.50"
#define WIFI_STATIC_NETMASK     "255.255.255.0"
#define WIFI_STATIC_GATEWAY     "192.168.1.1"

/*==============================================================================
 * 状态指示灯行为
 *============================================================================*/
/**
 * @brief 指示灯语义（对应 app_led_cfg.h 的 APP_LED_WIFI，即 g_led_wifi / GPIO5）
 *
 *   ┌────────────────────────┬──────────────┬────────────────────────────────┐
 *   │ WiFi 状态               │ 灯的表现      │ 用的图案                        │
 *   ├────────────────────────┼──────────────┼────────────────────────────────┤
 *   │ 初始化前 / 未开始        │ 灭           │ APP_LED_PAT_OFF                │
 *   │ 正在连接 / 正在获取 IP   │ 快闪 100ms   │ APP_LED_PAT_FAST_BLINK         │
 *   │ 连接成功（已拿到 IP）    │ ★ 常亮 ★     │ APP_LED_PAT_ON                 │
 *   │ 重连等待中（未超重试数） │ 慢闪 800ms   │ APP_LED_PAT_SLOW_BLINK         │
 *   │ 失败进入长退避           │ 双闪后长灭    │ APP_LED_PAT_DOUBLE_BLINK       │
 *   └────────────────────────┴──────────────┴────────────────────────────────┘
 *
 *   ★ 需求里明确「常亮表示已连接成功」，所以连接成功的图案是常亮，不是呼吸灯。
 *   ★ 本工程 5 个灯各有语义，WiFi 灯固定用 APP_LED_WIFI，不再单独配句柄。
 */
#define WIFI_LED_ID             APP_LED_WIFI

/*==============================================================================
 * 调试开关
 *============================================================================*/
/**
 * @brief 是否在连接成功后周期性打印 IP / 信号强度
 * @note  1 = 打印（调试用），0 = 只在连接成功那一刻打印一次。
 */
#define WIFI_LOG_RSSI_PERIODIC  1

#endif /* __APP_WIFI_CFG_H__ */
