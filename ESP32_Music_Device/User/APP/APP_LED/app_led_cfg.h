/**
 * @file app_led_cfg.h
 * @brief 指示灯配置（★ 要改灯的语义、点位、闪烁图案就改这里 ★）
 * @author 李嘉图
 * @date 2026-06-26
 *
 * @note 本工程一共 5 个语义指示灯，全部高电平点亮：
 *
 *   ┌──────────────┬───────┬────────┬─────────────────────────────────────────┐
 *   │ 句柄          │ 引脚  │ 语义   │ 表现                                     │
 *   ├──────────────┼───────┼────────┼─────────────────────────────────────────┤
 *   │ g_led_hb     │ GPIO4 │ 生命灯 │ 500ms 方波（亮500/灭500），由独立任务翻转  │
 *   │ g_led_wifi   │ GPIO5 │ WiFi   │ 常亮=已连上；快闪=连接中；慢闪=重连；双闪=失败 │
 *   │ g_led_mic    │ GPIO6 │ 录音   │ 亮=正在录音，灭=空闲                      │
 *   │ g_led_audio  │ GPIO7 │ 有音频 │ 常亮=有可播放音频；新音频载入时快闪三下     │
 *   │ g_led_backend│ GPIO8 │ 后端   │ 灭=WiFi没连；快闪=URL没填/请求中；常亮=可达；慢闪=失败 │
 *   │ g_led_spare  │ GPIO9 │ 预留   │ 未使用                                    │
 *   └──────────────┴───────┴────────┴─────────────────────────────────────────┘
 *
 *   引脚写在 bsp_gpio.c 的 GPIO_HW_MAP 里；本文件只管「语义 → 句柄」和图案。
 *   换灯只改下面的 APP_LED_TABLE 一行，业务代码完全不用动。
 */

#ifndef __APP_LED_CFG_H__
#define __APP_LED_CFG_H__

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stdint.h>
// 功能包含
#include "bsp_gpio.h"

/*==============================================================================
 * 逻辑 LED 编号
 *============================================================================*/
/**
 * @brief 逻辑 LED 编号（业务层用编号，不直接抓句柄）
 * @note  业务层写 App_LED_Set(APP_LED_MIC, &APP_LED_PAT_ON)，
 *        比 App_LED_SetPattern(g_led_mic, ...) 更好读，也让「换引脚」只影响配置表。
 */
typedef enum {
    APP_LED_HB      = 0,    /* 生命灯 */
    APP_LED_WIFI    = 1,    /* WiFi 状态 */
    APP_LED_MIC     = 2,    /* 正在录音 */
    APP_LED_AUDIO   = 3,    /* 有可播放音频 */
    APP_LED_BACKEND = 4,    /* 后端连通 */
    APP_LED_SPARE   = 5,    /* 预留 */

    APP_LED_COUNT   = 6,    /* 灯的总数（含预留） */
} App_LED_Id_t;

/*==============================================================================
 * 语义 → 句柄 映射表
 *============================================================================*/
/**
 * @brief 指示灯点位表：逻辑编号 → BSP 具名句柄
 * @note  ★ 顺序必须与 App_LED_Id_t 一一对应 ★
 *        这张表是运行期数组（句柄是运行期才确定取值的指针变量），
 *        所以定义在 app_led.c 里，这里只声明。
 */
extern const BSP_GPIO_Handle_t *const *App_LED_GetTable(void);

/*==============================================================================
 * 时序参数
 *============================================================================*/
/** @brief LED 状态机推进周期（毫秒），必须与 Task_LED 的周期一致 */
#define APP_LED_TICK_MS         10

/** @brief 生命灯翻转周期（毫秒）—— 亮 500 / 灭 500 的方波 */
#define APP_LED_HB_PERIOD_MS    500

/** @brief 新音频载入时的提示闪烁次数（快闪三下） */
#define APP_LED_AUDIO_FLASH_CNT 3

/**
 * @brief 生命灯是否由「独立任务」翻转（1 = 是，0 = 由 LED 状态机走图案）
 * @note  ★ 为什么要独立任务 ★
 *        生命灯的意义是「证明系统还活着」。如果它由 LED 状态机推进，
 *        那么当 LED 任务本身被饿死时，生命灯也会停 —— 这时你分不清
 *        「系统死了」还是「只是 LED 任务被挤了」，诊断价值就没了。
 *        独立任务（优先级 1，和 LED 任务同级）至少有独立的栈和调度实体，
 *        能覆盖「LED 状态机逻辑出错卡住」这一类故障。
 *        真正要覆盖「全局死锁」，需要的是硬件看门狗（后面可以加 esp_task_wdt）。
 */
#define APP_LED_HB_SEPARATE_TASK    1

#endif /* __APP_LED_CFG_H__ */
