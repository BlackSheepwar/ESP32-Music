#ifndef __TASK_WIFI_H__
#define __TASK_WIFI_H__

/*==============================================================================
 * 宏定义与常量
 *============================================================================*/
/**
 * @brief WiFi 状态机服务周期（毫秒）
 * @note  50ms 是权衡结果：
 *          - 再快：状态机大部分调用都是空转（只有时间戳比较），纯浪费 CPU
 *          - 再慢：连接成功到灯变常亮之间会有明显延迟，用户感觉「连上了灯还闪」
 *        注意这不是连接超时精度 —— 超时判定是拿时间戳比大小的，
 *        周期抖动只会让判定晚 ≤50ms，不影响正确性。
 */
#define WIFI_TASK_PERIOD_MS     50

/*==============================================================================
 * 任务函数
 *============================================================================*/
/**
 * @brief WiFi 服务任务
 * @param argument 未使用
 *
 * @note 职责：
 *         1. 调 App_WiFi_Init()（初始化 BSP_WIFI + 注册回调 + 载入配置宏）
 *         2. 每 WIFI_TASK_PERIOD_MS(50ms) 调一次 App_WiFi_Service() 推进状态机
 *
 *       ★ 本任务不做任何阻塞等待 —— 所以即使 WiFi 一直连不上，
 *         它也只是每 50ms 空转一次，不会拖累别的任务。
 *       ★ 任务优先级 4：低于按键分发（5），高于 LED（1）。
 *         理由：WiFi 状态机被延迟 50ms 无所谓，但要在 50ms 内响应；
 *         按键响应要最快，灯可以最慢。
 */
void Task_WiFi_Service(void *argument);

#endif /* __TASK_WIFI_H__ */
