/**
 * @file task_led.h
 * @brief LED 任务（服务推进 + 生命灯翻转，两个独立任务）
 * @author 李嘉图
 * @date 2026-06-26
 */

#ifndef __TASK_LED_H__
#define __TASK_LED_H__

/*==============================================================================
 * 任务函数
 *============================================================================*/
/**
 * @brief LED 服务任务（推进 5 个语义灯的闪烁相位）
 * @param argument 未使用
 *
 * @note 职责：
 *         1. 调 App_LED_Init()（配置指示灯引脚、点位表、全部置灭）
 *         2. 每 APP_LED_TICK_MS(10ms) 调一次 App_LED_Service() 推进相位
 *
 *       ★ 为什么给 LED 单独开一个任务：灯是「有人在等」的东西 ——
 *         如果它和 WiFi 状态机挤在同一个任务里，WiFi 一旦在连接阶段阻塞，
 *         灯就会卡住不闪，用户看到灯不动会以为死机。
 *       ★ 本任务不碰生命灯（生命灯归 Task_Heartbeat，见 app_led_cfg.h 的说明）。
 */
void Task_LED_Service(void *argument);

/**
 * @brief 生命灯任务（500ms 方波翻转）
 * @param argument 未使用
 *
 * @note ★ 这个任务的全部工作就是 vTaskDelay(500ms) + 翻转一次 GPIO ★
 *
 *       它存在的意义是「证明系统还活着」。刻意不做任何状态机判断、不查时间戳、
 *       不打日志 —— 代码路径越短，它自己出错的可能性就越低，
 *       于是「它不闪了」才真的等价于「系统出了问题」。
 *
 *       ★ 它只能覆盖「调度器还在跑但其他任务卡住」这类故障。
 *         要覆盖「全局死锁 / 中断异常」，需要硬件看门狗（esp_task_wdt），
 *         那个等接后端之后再加（现在加会因为有阻塞式 HTTP 而误触发）。
 *
 *       ★ 优先级 1（最低）：它不紧急，谁都能抢它的 CPU。
 *         反过来说，如果连优先级 1 的任务都跑不到，那系统确实出大问题了。
 */
void Task_Heartbeat(void *argument);

#endif /* __TASK_LED_H__ */
