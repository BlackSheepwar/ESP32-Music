#ifndef __TASK_AUDIO_H__
#define __TASK_AUDIO_H__

/*==============================================================================
 * 宏定义与常量
 *============================================================================*/
/**
 * @brief ★ 固定循环自检开关 ★
 *
 *   0 = 关闭（默认，推荐）：音频任务只做「建立 I2S + 服务录音/播放」。
 *       测试录音改用按键更灵活，而且不受任务时序约束：
 *         KEY3  按一下录固定 5 秒进本地回环缓冲
 *         KEY4  回放刚录的那段（单次）
 *
 *   1 = 打开：任务进入死循环，反复「录 3 秒 → 打印录到多少帧」。
 *       只在「想确认 I2S 时钟起没起、麦克风有没有数据」时临时打开。
 *       ★ 打开后按键的录音/播放会失效（任务被这个循环占住）★
 */
#define I2S_LOOPBACK_TEST       0

/** @brief 自检模式下的录音时长（秒） */
#define AUDIO_TEST_SECONDS      3

/*==============================================================================
 * 任务函数
 *============================================================================*/
/**
 * @brief 音频任务
 * @param argument 未使用
 *
 * @note ★ 优先级给到最高（6）是故意的 ★
 *       I2S 是硬实时外设，读 DMA 晚一点点就会 overflow 丢样点
 *       （听到「咔咔」爆音）。灯可以等，WiFi 可以等，音频不能等。
 *
 *       本任务是【唯一】直接操作 I2S 的地方：
 *         - 录音采集（App_Audio_Service 内部）
 *         - 播放推进（同上）
 *       其它任务通过 App_Audio_Play / App_Audio_RecordStart 入队请求，
 *       不直接碰 I2S —— 这样不会出现两个任务同时读写的竞态。
 */
void Task_Audio(void *argument);

#endif /* __TASK_AUDIO_H__ */
