#ifndef __TASK_KEY_H__
#define __TASK_KEY_H__

/*==============================================================================
 * 任务函数
 *============================================================================*/
/**
 * @brief 按键扫描任务（生产者）
 * @param argument 未使用
 *
 * @note 职责：
 *         1. 调 App_Key_Init()（配置引脚 + 建事件队列）
 *         2. 遍历 task_key_cfg.h 的 KEY_REG_TABLE 注册 4 个按键
 *         3. 每 KEY_SCAN_PERIOD_MS(10ms) 调一次 App_Key_Update()，事件自动入队
 *
 *       ★ 它只管「扫」，不处理业务 —— 业务在 Task_Key_Cmd 里。
 *         两者通过 FreeRTOS 队列解耦，业务再慢也不会漏掉按键。
 */
void Task_Key_Debounce(void *argument);

/**
 * @brief 按键命令分发任务（消费者）
 * @param argument 未使用
 *
 * @note 阻塞在按键事件队列上（不轮询、不占 CPU），收到事件后调
 *       App_Key_CMD_Packet() 分发。业务动作（录音、播放、重连…）都在那里。
 *
 *       ★★ 这个任务【绝对不能被长时间阻塞】（教训）★★
 *
 *       它曾经同步执行整条上传链路（TLS 握手 + 102KB body + 解析），
 *       实测最坏要 45 秒 / 一次 × 最多 5 次重试 ≈ 3.75 分钟。
 *       而按键消抖任务在此期间仍在往事件队列里塞事件（队列只有 16 深），
 *       于是队列装满、开始丢事件 —— 而本模块的事件
 *       （DOWN / CLICK / LONG / LONG_UP）**全部都是状态转换的唯一次机会**，
 *       丢任何一个都会让按键状态与上层记录永久不一致。实测表现：
 *       「第一次 KEY1 能录，第二次按 KEY1 完全没反应」。
 *
 *       ★ 所以上传搬到了 Task_Key_Upload ★ 本任务只负责"投递请求"，
 *         投递完立刻回去继续消费按键事件。
 */
void Task_Key_Cmd(void *argument);

/**
 * @brief 上传 worker 任务（把耗时的上传从按键任务里搬出来）
 * @param argument 未使用
 *
 * @note  ★ 为什么需要它 ★
 *        上传不是"一下就好"的操作：域名在国内是概率性可达的，
 *        单次可能耗 45 秒，失败还要重试（最多 5 次）。如果它在按键任务里
 *        同步跑，按键任务就有 45 秒 ~ 3.75 分钟不消费事件队列
 *        → 队列溢出 → 丢状态转换事件 → 按键状态机与上层记录不一致。
 *
 *        现在：Task_Key_Cmd 收到"松手上传"后只往上传请求队列投一条消息
 *        （深度 1 的计数信号量语义），立刻返回；本任务负责真正干活。
 *
 *        ★ 并发保护 ★ 本任务是唯一执行上传的地方，
 *          而"是否正在上传"这个状态也只有它自己读写 —— 所以不存在并发。
 *          重复请求在 Task_Key_Cmd 侧就会被拒（它会先看忙不忙）。
 */
void Task_Key_Upload(void *argument);

/**
 * @brief 查询上传 worker 是否正在忙
 * @retval 1: 正在上传
 * @retval 0: 空闲
 * @note  给 Task_Key_Cmd 用来拒绝"上传还没完又按 KEY1"的重复请求，
 *        避免把请求堆起来（堆起来也没用：WAV 缓冲只有一份，会被覆盖）。
 */
uint8_t Task_Key_UploadIsBusy(void);

#endif /* __TASK_KEY_H__ */
