/**
 * @file task_key_cfg.h
 * @brief 按键注册参数配置表（★ 要改按键行为就改这里 ★）
 * @author 李嘉图
 * @date 2026-06-18
 *
 * @note 把按键注册参数从任务里提取到本文件，Task 层只负责遍历这张表完成注册。
 *       新增按键 = 在表里加一行 + 在 bsp_gpio.c 的 GPIO_HW_MAP 里加一个句柄。
 *
 *       ★ 本工程与参考工程的关键差异：
 *         参考工程用 gpio_id（数字 1/2/3…）寻址 BSP，本工程严格用 BSP_GPIO 的
 *         具名句柄（g_key1 ~ g_key4）。句柄的引脚写死在 bsp_gpio.c 的映射表里，
 *         所以这张配置表里【看不到引脚号】—— 那是故意的，换板子只改映射表。
 *
 *       当前硬件：4 个独立按键，低电平按下（按下读到 0），另一端接 GND，
 *                引脚内部上拉（见 bsp_gpio.c 的 KEY_CFG 宏）。
 */

#ifndef __TASK_KEY_CFG_H__
#define __TASK_KEY_CFG_H__

/*==============================================================================
 * 头文件包含
 *============================================================================*/
// 固定包含
#include <stdint.h>
// 功能包含
#include "bsp_gpio.h"

/*==============================================================================
 * 宏定义与常量
 *============================================================================*/
/** @brief 按键扫描周期（毫秒）。10ms 足够，再快只是浪费 CPU */
#define KEY_SCAN_PERIOD_MS      10

/** @brief 消抖时长（毫秒）。20ms 能滤掉绝大多数机械抖动 */
#define KEY_DEBOUNCE_MS         20

/** @brief 长按判定阈值（毫秒）。2000ms 是「按住说话」的常见手感 */
#define KEY_LONG_PRESS_MS       2000

/** @brief 按键激活电平：0 = 低电平按下（本工程），1 = 高电平按下 */
#define KEY_ACTIVE_LEVEL        0

/*==============================================================================
 * 按键注册参数配置表
 *============================================================================*/
/**
 * @brief 按键注册表项
 * @note  ★ 表本身不放在这个头文件里，而是在 task_key.c 的函数内部定义 ★
 *        原因：g_key1 ~ g_key4 是 bsp_gpio.c 里定义的【指针变量】
 *        （extern const BSP_GPIO_Handle_t *const g_key1;），
 *        它们的值在运行期才确定，不是编译期常量，
 *        因此不能用来初始化文件作用域的 static const 数组
 *        （C 语言会报 "initializer element is not constant"）。
 *        放进函数体变成自动变量就没有这个限制。
 *
 *        引脚写在 bsp_gpio.c 的 GPIO_HW_MAP 里，所以这张表里看不到引脚号 —— 这是故意的。
 */
typedef struct {
    uint8_t                  key_id;            /* 逻辑按键 ID（分发表匹配用） */
    const BSP_GPIO_Handle_t *gpio;              /* BSP_GPIO 具名句柄 */
    uint16_t                 long_press_ms;     /* 长按判定阈值（毫秒） */
    uint8_t                  active_level;      /* 按键激活电平（0 = 低电平按下） */
    uint16_t                 debounce_ms;       /* 消抖时长（毫秒） */
} key_register_t;

/**
 * @brief 按键注册表的规模（表体在 task_key.c 的 Task_Key_Debounce 里）
 * @note  把 4 个按键的「业务身份」记在这里，后面接业务时按 key_id 分发：
 *          KEY1 (id 1) → 按住说话 / 开始录音（长按）
 *          KEY2 (id 2) → 停止播放
 *          KEY3 (id 3) → 切换音色
 *          KEY4 (id 4) → 强制重连 WiFi（已接好，见 task_key.c）
 */
#define KEY_REG_TABLE_SIZE      4

/*==============================================================================
 * 4 个按键的业务定义
 *============================================================================*/
/**
 *   KEY1 (id 1)  按住录音 → 松手停止并上传后端 → 解析 → 准备合成
 *                录音灯（LED3）跟着它亮灭；最长 8 秒自动停
 *
 *   KEY2 (id 2)  播放已有合成音乐（循环）/ 再按停止（下次从头开始）
 *                音频灯（LED4）跟着它走；载入新音乐时会闪三下
 *
 *   KEY3 (id 3)  回环测试：★ 按住录音 / 松手停止 ★（不上传，只存本地）
 *                ★ 不操作任何 LED ★
 *                松手后在串口打印诊断：frames / rms / peak / dc / clipped
 *                + 自动判读（比如"一个样点都没录到 → 查 VDD / L-R / 接线"）
 *
 *   KEY4 (id 4)  播放回环录音：按一下从头播一遍（不循环）
 *                播放中再按 → 停止；停止后再按 → 从头开始
 *                ★ 不操作任何 LED ★
 *
 * ★ 为什么 KEY3/KEY4 不点灯 ★
 *   录音灯和音频灯只表达「KEY1 在录音」和「有合成音乐」这两件事。
 *   如果回环测试也去点它们，两个功能同时在跑时灯的含义就乱了。
 *   回环测试改用串口输出判断，而且给的是定量结果（rms/peak/dc/clipped），
 *   比一个"亮/灭"信息量大得多 —— 麦克风到货后就是靠这组数字定位问题的。
 */

#endif /* __TASK_KEY_CFG_H__ */
